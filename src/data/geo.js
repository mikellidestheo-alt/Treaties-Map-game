// Hand-simplified low-poly geography. All coordinates are [longitude, latitude].
// The map is intentionally coarse: small islands and narrow territories are slightly
// exaggerated so they can be tapped on a touch screen.

/** Elliptical blob used for small islands. */
export function blob(lon, lat, rx = 0.6, ry = rx, n = 9, rot = 0) {
  const pts = [];
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2;
    const wob = 1 + 0.12 * Math.sin(i * 2.3 + lon);
    const x = Math.cos(a) * rx * wob;
    const y = Math.sin(a) * ry * wob;
    pts.push([lon + x * Math.cos(rot) - y * Math.sin(rot), lat + x * Math.sin(rot) + y * Math.cos(rot)]);
  }
  return pts;
}

